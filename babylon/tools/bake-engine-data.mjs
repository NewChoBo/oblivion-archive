import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync, gzipSync } from 'node:zlib';
import { Color3, NullEngine, PBRMaterial, Quaternion, Scene, Vector3 } from '@babylonjs/core';
import { chapterLevel, workLayout } from '../src/content/citadel-layout.ts';
import {
  buildCitadel,
  citadelLookoutBounds,
} from '../src/platform/babylon/citadel/floating-citadel.ts';
import {
  EXPERIENCE_LEVELS,
  EXPERIENCE_RULES,
  EXPERIENCES,
} from '../src/content/catalogs/experiences.ts';
import { ARENA_PISTOL, ARENA_RIFLE } from '../src/content/catalogs/firearms.ts';
import { english } from '../src/content/locales/experience.ts';
import { korean } from '../src/content/locales/ko/experience.ts';

// Geometry is generated by the same construction functions as the published survey. Local mesh
// coordinates and world TRS remain separate so the freight sequence moves its real colliders.
const engine = new NullEngine();
function publish(target, bytes) {
  if (process.argv.includes('--check')) {
    const compressed = target.pathname.endsWith('.gz');
    const content = (buffer) => (compressed ? gunzipSync(buffer) : Buffer.from(buffer));
    if (!content(readFileSync(target)).equals(content(bytes))) {
      throw new Error(
        'Outdated engine data ' + target.pathname + '. Run npm run assets:shared in babylon/.',
      );
    }
  } else {
    writeFileSync(target, bytes);
  }
}
const scene = new Scene(engine);
const colors = {};
const colliders = [];
const citadel = buildCitadel(scene, {
  colliders,
  entranceFrame: chapterLevel.doorFrames['south-entrance'],
  material(name, color) {
    const id = name.split(' · ').at(-1);
    colors[id] = color;
    const mat = new PBRMaterial(id, scene);
    mat.albedoColor = Color3.FromHexString(color);
    return mat;
  },
});
const meshes = scene.meshes.filter((m) => m.getTotalVertices() > 0);
const round = (n) => Math.round(n * 100000) / 100000;
const numbers = (v) => Array.from(v, round);
function pose(mesh) {
  const pos = new Vector3(),
    scale = new Vector3(),
    rot = new Quaternion();
  mesh.computeWorldMatrix(true).decompose(scale, rot, pos);
  return numbers([...pos.asArray(), ...rot.asArray(), ...scale.asArray()]);
}
const solid = new Set(colliders);
const parts = meshes.map((m) => ({
  name: m.name,
  material: m.material.name,
  collision: solid.has(m),
  visible: m.isVisible && m.visibility > 0,
  phase: m.isEnabled() ? 0 : -1,
  doubleSided: !m.material.backFaceCulling,
  pose: pose(m),
  positions: numbers(m.getVerticesData('position')),
  normals: numbers(m.getVerticesData('normal')),
  uv: numbers(m.getVerticesData('uv') ?? []),
  indices: Array.from(m.getIndices()),
}));
for (let i = 1; i <= 5; i++) {
  citadel.restore(i, true);
  meshes.forEach((m, j) => {
    if (parts[j].phase === -1 && m.isEnabled()) parts[j].phase = i;
  });
}
if (parts.some((m) => m.phase < 0)) throw Error('Unreachable exterior mesh');
citadel.restore(0, true);
citadel.restore(4);
const { liftSeconds, turnSeconds, lowerSeconds } = workLayout.freight;
const duration = liftSeconds + turnSeconds + lowerSeconds;
const frames = Math.ceil(duration * 12);
for (const m of citadel.movingShadowCasters) parts[meshes.indexOf(m)].motion = [];
for (let i = 0; i <= frames; i++) {
  if (i) citadel.update(duration / frames);
  for (const m of citadel.movingShadowCasters) parts[meshes.indexOf(m)].motion.push(pose(m));
}
const folder = new URL('../../asset-sources/Art/Chapter1/', import.meta.url);
publish(
  new URL('unity-citadel.json.gz', folder),
  gzipSync(
    JSON.stringify({
      version: 1,
      duration,
      colors,
      parts,
      lookout: citadelLookoutBounds,
      lamps: scene.lights.map((light) => ({
        position: numbers(light.position.asArray()),
        range: light.range,
        intensity: light.intensity,
      })),
    }),
    { level: 9 },
  ),
);
const arenaFolder = new URL('../../asset-sources/Art/arenas/', import.meta.url);
mkdirSync(arenaFolder, { recursive: true });
publish(
  new URL('experience-layouts.json', arenaFolder),
  JSON.stringify(
    {
      levels: EXPERIENCE_LEVELS,
      rules: EXPERIENCE_RULES,
      modes: EXPERIENCES,
      firearms: [ARENA_PISTOL, ARENA_RIFLE],
      text: { en: english, ko: korean },
    },
    null,
    2,
  ) + '\n',
);
console.log(
  meshes.length +
    ' exterior meshes, ' +
    solid.size +
    ' collision surfaces, ' +
    Object.keys(EXPERIENCES).length +
    ' modes',
);
engine.dispose();
